#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn source_roles_match_unicode_17() {
        assert_eq!(unicode_segmentation::UNICODE_VERSION, (17, 0, 0));
        for &(start, end, role) in ROLE_RANGES {
            assert!(start > 0x7f && start <= end && end <= u32::from(char::MAX));
            assert_ne!(role, Anchor);
        }
        for pair in ROLE_RANGES.windows(2) {
            let (_, end, role) = pair[0];
            let (next_start, _, next_role) = pair[1];
            assert!(end < next_start && (end + 1 < next_start || role != next_role));
        }
        // FNV-1a of the role bytes in scalar order, derived from the official
        // property file independently of ROLE_RANGES and checked against the
        // former fork. The fingerprint covers the default role and ASCII too.
        let mut hash = 0xcbf2_9ce4_8422_2325u64;
        for ch in '\0'..=char::MAX {
            let role = match source_role(ch) {
                Anchor => 0,
                Prepend => 1,
                Extend => 2,
                SpacingMark => 3,
                Zwj => 4,
                Control => 5,
            };
            hash = (hash ^ role).wrapping_mul(0x0100_0000_01b3);
        }
        assert_eq!(hash, 0x31ff_5545_496c_37be);
    }
}
