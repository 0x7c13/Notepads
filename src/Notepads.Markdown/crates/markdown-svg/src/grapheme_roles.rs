//! Scalar roles for SVG script resolution. Grapheme boundaries come from unicode-segmentation.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum SourceGraphemeRole {
    Anchor,
    Prepend,
    Extend,
    SpacingMark,
    Zwj,
    Control,
}
use SourceGraphemeRole::*;

const PAGE_SHIFT: u32 = 8;
const PAGE_COUNT: usize = 0x110000 >> PAGE_SHIFT;
// Index the first range whose end reaches each page boundary, including the sentinel.
const PAGE_STARTS: [u16; PAGE_COUNT + 1] = {
    assert!(ROLE_RANGES.len() <= u16::MAX as usize);
    let mut starts = [0; PAGE_COUNT + 1];
    let mut range = 0;
    let mut page = 0;
    while page < starts.len() {
        let first_scalar = (page as u32) << PAGE_SHIFT;
        while range < ROLE_RANGES.len() && ROLE_RANGES[range].1 < first_scalar {
            range += 1;
        }
        starts[page] = range as u16;
        page += 1;
    }
    starts
};

pub(super) fn source_role(ch: char) -> SourceGraphemeRole {
    if ch.is_ascii() {
        return if ch.is_ascii_control() {
            Control
        } else {
            Anchor
        };
    }
    let code = u32::from(ch);
    let page = (code >> PAGE_SHIFT) as usize;
    let start = usize::from(PAGE_STARTS[page]);
    let end = usize::from(PAGE_STARTS[page + 1]);
    let first_candidate =
        start + ROLE_RANGES[start..end].partition_point(|&(_, end, _)| end < code);
    // The range at the next page's index can start in this page and span its end.
    match ROLE_RANGES.get(first_candidate) {
        Some(&(start, _, role)) if start <= code => role,
        _ => Anchor,
    }
}

